const normalizeText = (value: string) =>
  value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();

const hashValue = (value: string) => {
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return Math.abs(hash);
};

function detectExperienceTheme(
  title: string,
  capital: string,
  context: string,
): ExperienceVisualTheme {
  const normalizedTitle = normalizeText(title);
  const normalizedCapital = normalizeText(capital);

  if (
    normalizedCapital &&
    (normalizedTitle === normalizedCapital ||
      normalizedTitle.includes(normalizedCapital))
  ) {
    return "city";
  }

  const match = experienceThemePatterns.find(({ pattern }) =>
    pattern.test(normalizedTitle),
  );
  if (match) return match.theme;

  const contextMatch = experienceThemePatterns.find(({ pattern }) =>
    pattern.test(normalizeText(context)),
  );
  return contextMatch?.theme ?? "heritage";
}

export function getExperienceVisual({
  slug,
  title,
  index,
  countryName,
  capital,
  context,
  fallbackImage,
  usedImages,
  preferFallback = false,
  explicitImage,
}: {
  slug: string;
  title: string;
  index: number;
  countryName: string;
  capital: string;
  context: string;
  fallbackImage?: string;
  usedImages: Set<string>;
  preferFallback?: boolean;
  explicitImage?: string;
}): { image: string; imageAlt: string } {
  if (explicitImage?.trim()) {
    usedImages.add(explicitImage);
    return { image: explicitImage, imageAlt: `${title}, ${countryName}` };
  }
  if (
    preferFallback &&
    fallbackImage &&
    !usedImages.has(fallbackImage)
  ) {
    usedImages.add(fallbackImage);
    return { image: fallbackImage, imageAlt: `${title}, ${countryName}` };
  }

  const primaryTheme = detectExperienceTheme(title, capital, context);
  const themes = [
    primaryTheme,
    ...experienceThemeOrder.filter((theme) => theme !== primaryTheme),
  ];
  const seed = hashValue(`${slug}::${title}::${index}`);

  let image: string | undefined;

  for (const theme of themes) {
    const pool = experienceImagePools[theme];
    for (let offset = 0; offset < pool.length; offset += 1) {
      const candidate = pool[(seed + offset) % pool.length];
      if (!usedImages.has(candidate)) {
        image = candidate;
        break;
      }
    }
    if (image) break;
  }

  const resolvedImage = image ?? fallbackImage ?? FALLBACK_COUNTRY_IMAGE;
  usedImages.add(resolvedImage);

  return {
    image: resolvedImage,
    imageAlt: `${title}, ${countryName}`,
  };
}
